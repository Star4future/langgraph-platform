import type { Metadata } from "next";
import { loadEvalData } from "@/lib/eval-data";

export const metadata: Metadata = { title: "Evals" };

const REPO = "https://github.com/Star4future/langgraph-platform";

function Check({ ok }: { ok: boolean }) {
  return <span className={ok ? "text-ok" : "text-err"}>{ok ? "✓" : "✗"}</span>;
}

export default async function EvalsPage() {
  const data = await loadEvalData();
  const failedCells = data.scenarios.filter((s) => !s.intent || !s.tools || !s.human);

  return (
    <main className="mx-auto w-full max-w-5xl px-4 py-8 sm:px-6">
      <h1 className="text-2xl font-semibold tracking-tight sm:text-3xl">
        Smoke-eval results — education vertical
      </h1>
      <p className="mt-2 text-sm text-ink-dim">
        Every number on this page is parsed at build time from two committed artefacts:{" "}
        <a
          href={`${REPO}/blob/main/eval/EVAL-RESULTS.md`}
          className="font-mono text-xs underline decoration-line underline-offset-2 hover:text-ink"
        >
          eval/EVAL-RESULTS.md
        </a>{" "}
        (generated by <span className="font-mono text-xs">eval/run_eval.py</span>) and{" "}
        <a
          href={`${REPO}/blob/main/eval/datasets/education_30.jsonl`}
          className="font-mono text-xs underline decoration-line underline-offset-2 hover:text-ink"
        >
          eval/datasets/education_30.jsonl
        </a>
        . Run recorded {data.runAt}.
      </p>

      {/* Honesty framing — the repo's own words, front and centre. */}
      <div className="mt-4 rounded-lg border border-warn/40 bg-warn/10 px-4 py-3 text-sm leading-6">
        <p className="font-medium text-warn">
          This is a smoke suite in deterministic mock mode — not a benchmark.
        </p>
        <p className="mt-1 text-ink-dim">
          The LLM is replaced by a keyword-matched mock, so these numbers exercise the{" "}
          <em>pipeline</em> — graph routing, tool dispatch, escalation logic, the retry loop and the
          judge — not model quality. The repository&apos;s own{" "}
          <a
            href={`${REPO}/blob/main/EXPERT-REVIEW.md`}
            className="underline decoration-line underline-offset-2 hover:text-ink"
          >
            expert review
          </a>{" "}
          says it plainly: thirty hand-written cases with deterministic mocks are “a smoke test, not
          a benchmark”. A live-LLM run is the follow-up — expect lower, noisier numbers there.
        </p>
      </div>

      {/* Summary metrics */}
      <h2 className="mt-8 text-lg font-medium">Summary metrics</h2>
      <div className="mt-3 grid gap-2 sm:grid-cols-2 lg:grid-cols-4">
        {data.metrics.map((m) => (
          <div key={m.metric} className="rounded-lg border border-line bg-surface px-3.5 py-3">
            <p className="text-xs text-ink-dim">{m.metric}</p>
            <p className="mt-1 font-mono text-xl">{m.value}</p>
            <p className="mt-0.5 text-[11px] text-ink-dim">
              threshold {m.threshold} <Check ok={m.pass} />
            </p>
          </div>
        ))}
      </div>

      {/* Breakdowns */}
      <div className="mt-8 grid gap-6 sm:grid-cols-2">
        {(
          [
            ["By category", data.byCategory],
            ["By difficulty", data.byDifficulty],
          ] as const
        ).map(([title, rows]) => (
          <div key={title}>
            <h2 className="text-lg font-medium">{title}</h2>
            <div className="mt-3 overflow-x-auto rounded-lg border border-line">
              <table className="w-full text-sm">
                <thead className="bg-surface text-left text-xs text-ink-dim">
                  <tr>
                    <th className="px-3 py-2 font-medium">{title.replace("By ", "")}</th>
                    <th className="px-3 py-2 font-medium">passed</th>
                    <th className="px-3 py-2 font-medium">rate</th>
                  </tr>
                </thead>
                <tbody>
                  {rows.map((r) => (
                    <tr key={r.key} className="border-t border-line">
                      <td className="px-3 py-2 font-mono text-xs">{r.key}</td>
                      <td className="px-3 py-2 text-ink-dim">
                        {r.passed}/{r.count}
                      </td>
                      <td className="px-3 py-2">{r.rate}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>
        ))}
      </div>

      {/* The imperfect cells, called out rather than buried */}
      <h2 className="mt-8 text-lg font-medium">Where the ✗ are</h2>
      <p className="mt-1 text-sm text-ink-dim">
        {failedCells.length} scenario{failedCells.length === 1 ? "" : "s"} miss a sub-check while
        still passing overall — they are why tool-choice and escalation precision sit below 100%,
        and they are listed here rather than averaged away.
      </p>
      <ul className="mt-2 space-y-1 text-sm">
        {failedCells.map((s) => (
          <li key={s.id} className="text-ink-dim">
            <span className="font-mono text-xs text-ink">{s.id}</span> —{" "}
            {[
              !s.intent ? "intent classification differed" : null,
              !s.tools ? "tool choice differed from the expected set" : null,
              !s.human ? "escalation flag differed from expectation" : null,
            ]
              .filter(Boolean)
              .join("; ")}
            {s.scenario && <span className="text-ink-dim"> (“{s.scenario.input}”)</span>}
          </li>
        ))}
      </ul>

      {/* Per-scenario join */}
      <h2 className="mt-8 text-lg font-medium">All 30 scenarios</h2>
      <p className="mt-1 text-sm text-ink-dim">
        Result rows joined with the dataset&apos;s inputs and expectations.
      </p>
      <div className="mt-3 overflow-x-auto rounded-lg border border-line">
        <table className="w-full min-w-[760px] text-sm">
          <thead className="bg-surface text-left text-xs text-ink-dim">
            <tr>
              <th className="px-3 py-2 font-medium">ID</th>
              <th className="px-3 py-2 font-medium">scenario</th>
              <th className="px-3 py-2 font-medium">category · difficulty</th>
              <th className="px-3 py-2 font-medium">intent</th>
              <th className="px-3 py-2 font-medium">tools</th>
              <th className="px-3 py-2 font-medium">human</th>
              <th className="px-3 py-2 font-medium">quality</th>
              <th className="px-3 py-2 font-medium">latency</th>
            </tr>
          </thead>
          <tbody>
            {data.scenarios.map((s) => (
              <tr key={s.id} className="border-t border-line align-top">
                <td className="px-3 py-2 font-mono text-xs">{s.id}</td>
                <td className="max-w-[280px] px-3 py-2 text-xs leading-5 text-ink-dim">
                  {s.scenario?.input ?? "—"}
                  {s.scenario && s.scenario.expected_tools.length > 0 && (
                    <span className="mt-0.5 block font-mono text-[10px]">
                      expects: {s.scenario.expected_tools.join(", ")}
                    </span>
                  )}
                </td>
                <td className="px-3 py-2 text-xs text-ink-dim">
                  {s.category} · {s.difficulty}
                </td>
                <td className="px-3 py-2">
                  <Check ok={s.intent} />
                </td>
                <td className="px-3 py-2">
                  <Check ok={s.tools} />
                </td>
                <td className="px-3 py-2">
                  <Check ok={s.human} />
                </td>
                <td className="px-3 py-2 font-mono text-xs">{s.quality}</td>
                <td className="px-3 py-2 font-mono text-xs">{s.latency}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </main>
  );
}
